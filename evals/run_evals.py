"""Run the eval set.

    python evals/run_evals.py              # retrieval metrics only, no API key needed
    python evals/run_evals.py --answers    # also answer every question with Claude

Writes evals/results/*.json and evals/RESULTS.md.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from datetime import date
from pathlib import Path

from bankrag.evaluate import (
    citation_ok,
    load_questions,
    numbers_match,
    page_key,
    percentile,
    retrieval_scores,
)
from bankrag.ingest.pipeline import load_chunks
from bankrag.retrieve.bm25 import BM25Retriever
from bankrag.retrieve.route import routed_search

EVAL_DIR = Path(__file__).resolve().parent
RESULTS_DIR = EVAL_DIR / "results"
K_VALUES = (1, 3, 6, 10)
SEARCH_DEPTH = 30  # how far down the ranking MRR looks


def retrieval_eval(questions, configs) -> list[dict]:
    rows = []
    answerable = [q for q in questions if q.answerable]
    for name, retriever, route, expand in configs:
        recalls = {k: [] for k in K_VALUES}
        rrs = []
        for q in answerable:
            for k in K_VALUES:
                # Search at each k, because routing splits k between banks: the top k of a
                # deeper search is not what the answer model would get. k counts chunks.
                hits = routed_search(retriever, q.question, k=k, route=route, expand=expand)
                recall, _ = retrieval_scores(q, [page_key(h.chunk) for h in hits], k)
                recalls[k].append(recall)
            hits = routed_search(retriever, q.question, k=SEARCH_DEPTH, route=route, expand=expand)
            pages = list(dict.fromkeys(page_key(h.chunk) for h in hits))
            rrs.append(retrieval_scores(q, pages, SEARCH_DEPTH)[1])
        row = {"config": name, "questions": len(answerable), "mrr": statistics.mean(rrs)}
        row.update({f"recall@{k}": statistics.mean(v) for k, v in recalls.items()})
        rows.append(row)
    return rows


def answer_eval(questions, retriever, k: int) -> tuple[list[dict], dict]:
    from bankrag.answer.generate import answer, log_trace

    records = []
    for q in questions:
        hits = routed_search(retriever, q.question, k=k)
        ans = answer(q.question, hits)
        log_trace(ans, {"eval_id": q.id})
        num_ok = numbers_match(q, ans.text) if q.answerable else None
        cites = [citation_ok(q, f"{s.bank}-{s.year}-p{s.page}", s.cited_text) for s in ans.sources]
        records.append(
            {
                "id": q.id,
                "category": q.category,
                "answerable": q.answerable,
                "refused": ans.refused,
                "numbers_ok": num_ok,
                "has_citation": bool(ans.sources),
                "citations_ok": all(cites) if cites else None,
                "cost_usd": ans.cost_usd,
                "latency_s": ans.latency_s,
                "cache_read_tokens": ans.cache_read_tokens,
                "answer": ans.text,
                "sources": [s.label for s in ans.sources],
            }
        )
        status = "REFUSED" if ans.refused else ("ok" if num_ok in (True, None) else "WRONG NUMBER")
        print(f"  {q.id} {status:12s} {ans.latency_s:4.1f}s  {ans.text[:90]!r}")

    ans_q = [r for r in records if r["answerable"]]
    unans = [r for r in records if not r["answerable"]]
    numeric = [r for r in ans_q if r["numbers_ok"] is not None]
    cited = [r for r in ans_q if r["citations_ok"] is not None]
    costs = [r["cost_usd"] for r in records]
    lat = [r["latency_s"] for r in records]
    summary = {
        "numeric_exact": sum(r["numbers_ok"] for r in numeric) / len(numeric) if numeric else None,
        "numeric_n": len(numeric),
        "answered_with_citation": sum(r["has_citation"] and not r["refused"] for r in ans_q) / len(ans_q),
        "citations_correct": sum(r["citations_ok"] for r in cited) / len(cited) if cited else None,
        "false_refusals": sum(r["refused"] for r in ans_q),
        "unanswerable_refused": sum(r["refused"] for r in unans),
        "unanswerable_n": len(unans),
        "cost_usd_mean": statistics.mean(costs),
        "cost_usd_p95": percentile(costs, 95),
        "latency_s_mean": statistics.mean(lat),
        "latency_s_p95": percentile(lat, 95),
    }
    return records, summary


def write_results_md(retrieval: list[dict], answers: dict | None, n_questions: int) -> None:
    lines = [
        "# Eval results",
        "",
        f"Generated by `evals/run_evals.py` on {date.today().isoformat()} over {n_questions} questions.",
        "Do not edit by hand.",
        "",
        "## Retrieval",
        "",
        "Recall@k: share of a question's evidence groups (one per bank or year it needs) with a gold page",
        "among the top k chunks, averaged over answerable questions. MRR: mean reciprocal rank of the first",
        "gold page in the top 30. Routed: search only the banks and years the question names.",
        "Danish glossary: add English report wording for Danish finance terms.",
        "",
        "| Config | " + " | ".join(f"Recall@{k}" for k in K_VALUES) + " | MRR |",
        "|---|" + "---|" * (len(K_VALUES) + 1),
    ]
    for r in retrieval:
        cells = " | ".join(f"{r[f'recall@{k}']:.2f}" for k in K_VALUES)
        lines.append(f"| {r['config']} | {cells} | {r['mrr']:.2f} |")
    if answers:
        a = answers
        lines += [
            "",
            "## Answers",
            "",
            "| Metric | Value |",
            "|---|---|",
            f"| Numeric answers exact | {a['numeric_exact']:.0%} of {a['numeric_n']} |",
            f"| Answerable questions answered with a citation | {a['answered_with_citation']:.0%} |",
            f"| Answers whose citations all check out | {a['citations_correct']:.0%} |",
            f"| Answerable questions wrongly refused | {a['false_refusals']} |",
            f"| Unanswerable questions refused | {a['unanswerable_refused']} of {a['unanswerable_n']} |",
            f"| Cost per question, mean / p95 (USD) | {a['cost_usd_mean']:.5f} / {a['cost_usd_p95']:.5f} |",
            f"| Latency per question, mean / p95 (s) | {a['latency_s_mean']:.1f} / {a['latency_s_p95']:.1f} |",  # noqa: E501
        ]
    (EVAL_DIR / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser()
    parser.add_argument("--answers", action="store_true", help="also run the answer evals (needs an API key)")
    parser.add_argument("--k", type=int, default=6, help="chunks passed to the answer model")
    args = parser.parse_args()

    questions = load_questions(EVAL_DIR / "questions.yaml")
    structure = BM25Retriever(load_chunks("structure"))
    fixed = BM25Retriever(load_chunks("fixed"))
    # (name, retriever, route by bank and year, expand Danish terms)
    configs = [
        ("BM25, fixed chunks", fixed, False, False),
        ("BM25, structure chunks", structure, False, False),
        ("BM25, structure chunks, routed", structure, True, False),
        ("BM25, structure chunks, routed, Danish glossary", structure, True, True),
    ]
    retrieval = retrieval_eval(questions, configs)
    RESULTS_DIR.mkdir(exist_ok=True)
    (RESULTS_DIR / "retrieval.json").write_text(json.dumps(retrieval, indent=2), encoding="utf-8")
    for r in retrieval:
        recalls = "  ".join(f"R@{k} {r[f'recall@{k}']:.2f}" for k in K_VALUES)
        print(f"{r['config']:50s} {recalls}  MRR {r['mrr']:.2f}")

    summary = None
    if args.answers:
        print("\nanswering...")
        records, summary = answer_eval(questions, structure, args.k)
        (RESULTS_DIR / "answers.json").write_text(
            json.dumps({"summary": summary, "records": records}, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
        print(json.dumps(summary, indent=2))

    write_results_md(retrieval, summary, len(questions))
    return 0


if __name__ == "__main__":
    sys.exit(main())
